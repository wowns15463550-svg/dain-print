const norm = (s: string) => s.toLowerCase().replace(/[\s.,!?~·'"()\-]/g, "");
const score = (t: string, keys: string[]) => {
  let s = 0;
  for (const k of keys) {
    const n = norm(k);
    if (t.includes(n)) s = Math.max(s, n.length) + (s ? 1 : 0);
  }
  return s;
};

// 질문에서 가장 잘 맞는 답 찾기. 하지 않는 작업이 더 정확히 맞으면 그 한 줄만.
export function findIntent(text: string): { best?: Intent; also: Intent[] } {
  const t = norm(text);
  if (!t) return { also: [] };
  const hits = INTENTS.map((it) => ({ it, s: score(t, it.keys) }))
    .filter((x) => x.s > 0)
    .sort((a, b) => b.s - a.s);
  let nope: { name: string; s: number } | undefined;
  for (const [name, keys] of NOPE) {
    const s = score(t, keys);
    if (s > 0 && (!nope || s > nope.s)) nope = { name, s };
  }
  if (nope && (!hits[0] || nope.s > hits[0].s || ["cant", "small", "kakao"].includes(hits[0].it.id))) {
    return { best: { id: "nope", keys: [], a: nopeAnswer(nope.name), mood: "sad" }, also: [] };
  }
  return { best: hits[0]?.it, also: hits.slice(1, 2).map((x) => x.it) };
}
