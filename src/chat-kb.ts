// 받침 있으면 "을", 없으면 "를"
const josa = (w: string) => {
  const c = w.replace(/\(.*\)$/, "").trim().slice(-1).charCodeAt(0);
  if (c >= 0xac00 && c <= 0xd7a3) return (c - 0xac00) % 28 ? "을" : "를";
  return "을";
};
